#!/usr/bin/env node
'use strict';
// Regenerates src/components/iconData.ts from an installed lucide-react package.
// Usage: node scripts/generate-icon-data.cjs <path-to-lucide-react>
// The website already depends on lucide-react, so app and web share one icon geometry.
// Lucide is ISC licensed; the license text ships in assets/icons/LICENSE.txt.
const fs = require('node:fs');
const path = require('node:path');

const source = process.argv[2];
if (!source) throw new Error('Pass the lucide-react package directory.');
const pkg = JSON.parse(fs.readFileSync(path.join(source, 'package.json'), 'utf8'));
const iconsDir = path.join(source, 'dist', 'esm', 'icons');

// App name -> Lucide name. Keep the list curated: every icon must earn its place.
const icons = {
  search: 'search', saved: 'heart', trips: 'luggage', account: 'user-round', support: 'headset',
  calendar: 'calendar-days', calendarCheck: 'calendar-check', filter: 'sliders-horizontal', map: 'map', pin: 'map-pin',
  chevron: 'chevron-right', chevronDown: 'chevron-down', back: 'arrow-left', forward: 'arrow-right',
  bed: 'bed-double', users: 'users-round', check: 'check', checkCircle: 'circle-check', info: 'info',
  meal: 'utensils', coffee: 'coffee', compare: 'columns-2', close: 'x', clock: 'clock', star: 'star',
  sort: 'arrow-up-down', list: 'list', plus: 'plus', minus: 'minus', card: 'credit-card', shield: 'shield-check',
  receipt: 'receipt-text', voucher: 'file-text', download: 'download', phone: 'phone', mail: 'mail', copy: 'copy',
  external: 'external-link', alert: 'triangle-alert', alertCircle: 'circle-alert', refresh: 'refresh-cw',
  offline: 'wifi-off', key: 'key-round', moon: 'moon', sparkles: 'sparkles', home: 'house', edit: 'pencil',
  globe: 'globe', logout: 'log-out', bell: 'bell', trash: 'trash-2', image: 'image', door: 'door-open',
  wallet: 'wallet', lock: 'lock', badgeCheck: 'badge-check', fileUp: 'file-up', hourglass: 'hourglass',
  hotel: 'hotel', navigation: 'navigation', share: 'share-2', history: 'history', compass: 'compass',
};
// Icons whose meaning depends on reading direction. Only these mirror in RTL.
const directional = ['chevron', 'back', 'forward', 'logout'];

function readNode(name) {
  const file = path.join(iconsDir, name + '.mjs');
  const text = fs.readFileSync(file, 'utf8');
  // Renamed icons are published as aliases that re-export their current module.
  const alias = text.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (alias) return readNode(alias[1]);
  const match = text.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!match) throw new Error('Could not read icon data for ' + name);
  // The data literal only contains objects, arrays, strings and numbers.
  const { node } = Function('"use strict";return (' + match[1] + ');')();
  if (!Array.isArray(node)) throw new Error('Missing icon node for ' + name);
  return node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    if (!['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'].includes(tag)) throw new Error('Unsupported tag ' + tag + ' in ' + name);
    return [tag, rest];
  });
}

const data = Object.fromEntries(Object.entries(icons).map(([app, lucide]) => [app, readNode(lucide)]));
const header = `// Generated by scripts/generate-icon-data.cjs from lucide-react ${pkg.version} (ISC, see assets/icons/LICENSE.txt).
// 24x24 grid, stroke-based geometry. Do not edit by hand; regenerate instead.
`;
const body = `export type IconElement = readonly [string, Readonly<Record<string, string | number>>];
export const iconData = ${JSON.stringify(data, null, 0).replace(/\],"/g, '],\n  "')} as const satisfies Record<string, readonly IconElement[]>;
export type IconName = keyof typeof iconData;
/** Icons that describe reading direction. Only these are mirrored in right-to-left layouts. */
export const directionalIcons: ReadonlySet<IconName> = new Set<IconName>(${JSON.stringify(directional)});
`;
const target = path.join(__dirname, '..', 'src', 'components', 'iconData.ts');
fs.writeFileSync(target, header + body);
console.log('Wrote', Object.keys(data).length, 'icons to', path.relative(process.cwd(), target));
